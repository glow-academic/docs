#!/usr/bin/env node
// Generates components/demo-manifest.ts by scanning public/demos/*.{webm,mp4}.
//
// The manifest lists every per-topic demo video on disk so
// <DemoVideo topic="..."/> can pick the right ``src`` up front — no
// "request per-topic → 404 → swap to placeholder" round-trip on page load.
//
// Both .webm (Playwright client recordings) and .mp4 (VHS CLI recordings,
// or hand-captured screen videos) are first-class. When both exist for a
// topic, .webm wins — it's the lossless format our recorder pipeline
// generates and plays natively in every modern browser.
//
// Run manually (re-run after dropping a new clip):
//   node scripts/gen-demo-manifest.mjs
//
// Wired into ``make sync-types`` so the manifest is regenerated as part
// of the canonical refresh flow.

import { readdirSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const DEMOS_DIR = join(ROOT, 'public', 'demos')
const OUT_FILE = join(ROOT, 'components', 'demo-manifest.ts')

let entries = []
try {
  entries = readdirSync(DEMOS_DIR)
} catch {
  // Directory missing — emit empty manifest so the build still works.
}

// topic → 'webm' | 'mp4'. .webm wins when both exist for the same topic.
const byTopic = new Map()
for (const file of entries) {
  if (file === '_placeholder.mp4') continue
  const m = file.match(/^(.+)\.(webm|mp4)$/)
  if (!m) continue
  const [, topic, ext] = m
  if (byTopic.get(topic) === 'webm') continue
  byTopic.set(topic, ext)
}

const sorted = [...byTopic.entries()].sort(([a], [b]) => a.localeCompare(b))

const body = `// AUTO-GENERATED by scripts/gen-demo-manifest.mjs — do not edit by hand.
// Each entry maps a topic slug to the file extension on disk
// (.webm for Playwright client recordings, .mp4 for VHS CLI recordings
// or hand-captured screen videos). When both exist, .webm wins.
// Regenerate via \`node scripts/gen-demo-manifest.mjs\` (or \`make sync-types\`).

export type DemoVideoExt = 'webm' | 'mp4'

export const DEMO_TOPICS: ReadonlyMap<string, DemoVideoExt> = new Map([
${sorted.map(([t, ext]) => `  ['${t}', '${ext}'],`).join('\n')}
])
`

mkdirSync(dirname(OUT_FILE), { recursive: true })
writeFileSync(OUT_FILE, body, 'utf8')
console.log(`✓ wrote ${sorted.length} topic(s) to components/demo-manifest.ts`)
