#!/usr/bin/env node
// Generates components/demo-manifest.ts by scanning public/demos/*.mp4.
//
// The manifest lists every per-topic demo video that exists on disk so
// <DemoVideo topic="..."/> can pick the right ``src`` up front — no more
// "request per-topic → 404 → swap to placeholder" round-trip on every
// page load.
//
// Run manually (re-run after dropping a new clip):
//   node scripts/gen-demo-manifest.mjs
//
// Wired into ``make sync-types`` so the manifest is regenerated as part
// of the canonical refresh flow.

import { readdirSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const DEMOS_DIR = join(ROOT, 'public', 'demos')
const OUT_FILE = join(ROOT, 'components', 'demo-manifest.ts')

let entries = []
try {
  entries = readdirSync(DEMOS_DIR)
} catch {
  // Directory missing — emit empty manifest so the build still works.
}

const topics = entries
  .filter((f) => f.endsWith('.mp4') && f !== '_placeholder.mp4')
  .map((f) => f.replace(/\.mp4$/, ''))
  .sort()

const body = `// AUTO-GENERATED by scripts/gen-demo-manifest.mjs — do not edit by hand.
// Lists every per-topic demo video present in public/demos/.
// Regenerate via \`node scripts/gen-demo-manifest.mjs\` (or \`make sync-types\`).

export const DEMO_TOPICS: ReadonlySet<string> = new Set([
${topics.map((t) => `  '${t}',`).join('\n')}
])
`

mkdirSync(dirname(OUT_FILE), { recursive: true })
writeFileSync(OUT_FILE, body, 'utf8')
console.log(`✓ wrote ${topics.length} topic(s) to components/demo-manifest.ts`)
